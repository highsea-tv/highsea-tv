function t(
  id: string,
  title: string,
  year: number,
  runtime: string,
  genre: string,
  rating: number,
  quality: string[],
  synopsis: string,
): Title {
  return { id, title, year, runtime, genre, rating, quality, synopsis }
}

/** All forty titles: the ten open movies first, then the rest. */
export const library: Title[] = [...titles, ...moreTitles]

export const art = (t: Title) => ({
  poster: posterArt(t.title),
  still: stillArt(t.title),
  backdrop: backdropArt(t.title),
})

export const byId = (id: string) => library.find((t) => t.id === id) as Title
