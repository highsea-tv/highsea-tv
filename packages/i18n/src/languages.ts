/**
 * A language's name ("Brazilian Portuguese"). `translations` (a locale's names, by the same codes)
 * wins where it has the code. A regional tag the catalog doesn't list (`en-GB`) takes its base
 * language's name; a code it doesn't know at all shows as itself.
 */
export function languageName(
  code: string,
  translations: Partial<Record<string, string>> = {},
): string {
  if (!code) return code
  const names: Partial<Record<string, string>> = languageNames
  const look = (c: string) => translations[c] ?? names[c]
  const exact = look(code)
  if (exact) return exact
  // Tags arrive in any case and with `_` (`pt_br`): match the catalog's own spelling.
  const tag = code.replace(/_/g, '-').toLowerCase()
  const listed = Object.keys(names).find((c) => c.toLowerCase() === tag)
  const base = tag.split('-')[0] ?? ''
  return (listed && look(listed)) || look(base) || code
}
