// Outlines the wordmark and tagline from Geist, so logo files never depend on an installed font.
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tracking } from '@highsea/tokens'
import opentype from 'opentype.js'

const require = createRequire(import.meta.url)
const SANS = require.resolve('geist/package.json').replace('package.json', 'dist/fonts/geist-sans/')

function load(file: string): opentype.Font {
  const b = readFileSync(SANS + file)
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer)
}

/** Outlines are drawn at 100 units per em, in a CSS line box with `line-height: 1`. */
export const EM = 100

export type Run = { font: 'regular' | 'medium' | 'semibold'; text: string }
export type Outlined = {
  /** One path per run, in line-box coordinates (y down, top of the line box at 0). */
  paths: string[]
  /** Advance width without trailing tracking. */
  width: number
  baseline: number
  ink: { x0: number; y0: number; x1: number; y1: number }
}

const f2 = (n: number) => String(Math.round(n * 100) / 100)

/** SVG path data from opentype commands (its own `toPathData` emits NaN for some values). */
function pathData(commands: opentype.PathCommand[]) {
  return commands
    .map((c) => {
      if (c.type === 'Z') return 'Z'
      if (c.type === 'Q') return `Q${f2(c.x1)} ${f2(c.y1)} ${f2(c.x)} ${f2(c.y)}`
      if (c.type === 'C')
        return `C${f2(c.x1)} ${f2(c.y1)} ${f2(c.x2)} ${f2(c.y2)} ${f2(c.x)} ${f2(c.y)}`
      return `${c.type}${f2(c.x)} ${f2(c.y)}`
    })
    .join('')
}

/** Lays text out as a browser does: GPOS kerning within a run, letter-spacing after every letter but the last. */
export function outline(runs: Run[], track: number): Outlined {
  const fonts = {
    regular: load('Geist-Regular.ttf'),
    medium: load('Geist-Medium.ttf'),
    semibold: load('Geist-SemiBold.ttf'),
  }
  const ref = fonts.semibold
  const { ascender, descender } = ref
  const scale = EM / ref.unitsPerEm
  // line-height 1: the half-leading splits (1em − content height) above and below
  const baseline = ((ref.unitsPerEm - (ascender - descender)) / 2 + ascender) * scale
  const total = runs.reduce((n, r) => n + [...r.text].length, 0)
  const ink = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity }
  let x = 0
  let i = 0
  const paths = runs.map((run) => {
    const font = fonts[run.font]
    const glyphs = font.stringToGlyphs(run.text)
    const parts = glyphs.map((g, k) => {
      const path = g.getPath(x, baseline, EM)
      const box = path.getBoundingBox()
      if (box.x1 < box.x2) {
        ink.x0 = Math.min(ink.x0, box.x1)
        ink.y0 = Math.min(ink.y0, box.y1)
        ink.x1 = Math.max(ink.x1, box.x2)
        ink.y1 = Math.max(ink.y1, box.y2)
      }
      const next = glyphs[k + 1]
      x += (g.advanceWidth ?? 0) * scale
      // pairs without a GPOS entry come back undefined
      if (next) x += (font.getKerningValue(g, next) || 0) * scale
      if (++i < total) x += track * EM
      return pathData(path.commands)
    })
    return parts.join('')
  })
  const r = (n: number) => Math.round(n * 100) / 100
  return {
    paths,
    width: r(x),
    baseline: r(baseline),
    ink: { x0: r(ink.x0), y0: r(ink.y0), x1: r(ink.x1), y1: r(ink.y1) },
  }
}

export const TAGLINE = 'Your own streaming platform, fully yours.'

/** The generated `src/wordmark-data.ts`. */
export function wordmarkDataTs(): string {
  const wordmark = outline(
    [
      { font: 'semibold', text: 'highsea' },
      { font: 'medium', text: ' tv' },
    ],
    tracking.wordmark,
  )
  const tagline = outline([{ font: 'regular', text: TAGLINE }], tracking.title)
  return `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/build.ts from Geist (OFL-1.1). Do not edit.
// Units: ${EM} per em, y down, in a CSS line box with line-height 1.

export const wordmarkOutline = ${JSON.stringify(wordmark, null, 2)} as const

export const taglineOutline = ${JSON.stringify({ text: TAGLINE, ...tagline }, null, 2)} as const
`
}
