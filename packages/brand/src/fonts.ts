import { weights } from '@highsea-tv/tokens'

/** Variable fonts for the web, declared by `@highsea-tv/brand/fonts.css`. */
export const WEB_FONTS = {
  sans: 'Geist-Variable.woff2',
  mono: 'GeistMono-Variable.woff2',
} as const

type Weight = keyof typeof weights
const WEIGHT_NAMES: Record<Weight, string> = {
  regular: 'Regular',
  medium: 'Medium',
  semibold: 'SemiBold',
}

/**
 * React Native needs one static file per weight. Register them under these names
 * (`useFonts(nativeFontFiles)` with each value `require`d), then set `fontFamily` with
 * `nativeFontFamily()`.
 */
export const NATIVE_FONTS: readonly string[] = (['Geist', 'GeistMono'] as const).flatMap((f) =>
  (Object.keys(weights) as Weight[]).map((w) => `${f}-${WEIGHT_NAMES[w]}`),
)

export function nativeFontFamily(family: 'sans' | 'mono', weight: Weight = 'regular'): string {
  return `${family === 'sans' ? 'Geist' : 'GeistMono'}-${WEIGHT_NAMES[weight]}`
}

/** Every file in `fonts/`. */
export const FONT_FILES: readonly string[] = [
  WEB_FONTS.sans,
  WEB_FONTS.mono,
  ...NATIVE_FONTS.map((n) => `${n}.ttf`),
]

/** `fonts/fonts.css`. */
export function fontsCss(): string {
  const face = (family: string, file: string) => `@font-face {
  font-family: '${family}';
  src: url('./${file}') format('woff2');
  font-weight: 100 900;
  font-style: normal;
  font-display: swap;
}
`
  return `/* SPDX-License-Identifier: OFL-1.1 (fonts) AND AGPL-3.0-only (this file) */
/* Generated by packages/brand/scripts/build.ts. Do not edit. */
${face('Geist', WEB_FONTS.sans)}
${face('Geist Mono', WEB_FONTS.mono)}`
}
