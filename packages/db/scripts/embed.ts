// Writes drizzle-kit's SQL migrations into src/migrations.ts, in journal order, so the server
// carries them without reading files at run time. `--check` fails when the file is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8')) as {
  entries: { tag: string }[]
}
const items = journal.entries.map((e) => ({
  tag: e.tag,
  sql: readFileSync(join(root, 'drizzle', `${e.tag}.sql`), 'utf8'),
}))
const out = `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/embed.ts from drizzle/. Don't edit: change the schema, then \`bun run generate\`.
export type Migration = { tag: string; sql: string }

export const migrations: Migration[] = ${JSON.stringify(items, null, 2)}
`
const target = join(root, 'src/migrations.ts')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) {
    console.error('src/migrations.ts is stale: run `bun run generate` in packages/db')
    process.exit(1)
  }
  console.log('migrations up to date')
} else {
  writeFileSync(target, out)
  console.log(`wrote ${items.length} migrations`)
}
