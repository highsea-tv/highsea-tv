// Generates the web outputs: plain CSS custom properties, and a Tailwind v4 theme.
// Both use the same variable names, so components work with or without Tailwind.
import { formatCss, parseColor } from './color.ts'
import { durations, springs, springToCss } from './motion.ts'
import { COLOR_ROLES } from './roles.ts'
import {
  aspect,
  blur,
  breakpoints,
  density,
  elevation,
  focus,
  radius,
  SPACE_BASE,
  shadowCss,
  tv,
} from './scales.ts'
import { type ResolvedTheme, resolveTheme } from './theme.ts'
import { builtInThemes } from './themes.ts'
import {
  adminText,
  fonts,
  type TextStyle,
  tracking,
  tvText,
  webText,
  weights,
} from './typography.ts'

type Entries = [name: string, value: string | number][]

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/\./g, '_')
const num = (n: number) => Number(n.toFixed(4))
const rem = (px: number) => `${num(px / 16)}rem`
const u = (n: number) => `${num(n)}cqw`
/** A rule of custom properties; `raw` lines (plain declarations) come first. */
const block = (selector: string, entries: Entries, indent = '', raw: string[] = []) =>
  `${indent}${selector} {\n${[...raw, ...entries.map(([k, v]) => `--${k}: ${v};`)]
    .map((line) => `${indent}  ${line}`)
    .join('\n')}\n${indent}}`

const HEADER = `/* SPDX-License-Identifier: AGPL-3.0-only */
/* Generated by @highsea-tv/tokens. Do not edit; run \`bun run build\` in packages/tokens. */`

// ---- theme-dependent variables

/** Every variable a theme sets. Custom themes use this too (server branding, theme editor). */
export function themeEntries(theme: ResolvedTheme): Entries {
  const s = theme.focusRingScale
  const ring = focus.tv.shadow
  return [
    ...COLOR_ROLES.map((r): [string, string] => [
      `color-${r}`,
      formatCss(parseColor(theme.colors[r])),
    ]),
    ['focus-ring-width', `${num(focus.web.width * s)}px`],
    ['focus-ring-offset', `${focus.web.offset}px`],
    ['tv-focus-ring-width', u(focus.tv.width * s)],
    [
      'tv-focus-shadow',
      `0 0 0 ${u(focus.tv.width * s)} ${formatCss(parseColor(theme.colors.text))}, ${ring.x} ${u(ring.y)} ${u(ring.blur)} ${u(ring.spread)} rgb(0 0 0 / ${ring.opacity})`,
    ],
  ]
}

export function themeCss(theme: ResolvedTheme, selector = `[data-theme="${theme.id}"]`): string {
  return block(selector, themeEntries(theme), '', ['color-scheme: dark;'])
}

const themeBlocks = () =>
  Object.values(builtInThemes)
    .map((spec) =>
      themeCss(
        resolveTheme(spec),
        spec.id === 'default' ? ':root,\n[data-theme="default"]' : `[data-theme="${spec.id}"]`,
      ),
    )
    .join('\n\n')

// ---- theme-independent variables

const textEntries = (name: string, t: TextStyle): Entries => [
  [`text-${name}`, rem(t.size)],
  ...(t.leading ? ([[`text-${name}--line-height`, t.leading]] as Entries) : []),
  ...(t.tracking ? ([[`text-${name}--letter-spacing`, `${t.tracking}em`]] as Entries) : []),
  [`text-${name}--font-weight`, t.weight],
]

const stack = (f: { family: string; fallback: readonly string[] }) =>
  [`'${f.family}'`, ...f.fallback].join(', ')

const base = springToCss(springs.base)
const quick = springToCss(springs.quick)

/** Variables Tailwind turns into utilities (`bg-s1`, `text-title`, `rounded-md`, `shadow-3`…). */
function utilityEntries(): Entries {
  const def = resolveTheme(builtInThemes.default)
  return [
    ...COLOR_ROLES.map((r): [string, string] => [
      `color-${r}`,
      formatCss(parseColor(def.colors[r])),
    ]),
    ['font-sans', stack(fonts.sans)],
    ['font-mono', stack(fonts.mono)],
    ...Object.entries(weights).map(([k, v]): [string, number] => [
      `font-weight-${k === 'regular' ? 'normal' : k}`,
      v,
    ]),
    ...Object.entries({ ...webText, ...adminText }).flatMap(([k, t]) => textEntries(k, t)),
    ...Object.entries(tracking).map(([k, v]): [string, string] => [`tracking-${k}`, `${v}em`]),
    ['spacing', rem(SPACE_BASE)],
    ...Object.entries(radius)
      .filter(([k]) => k !== 'pill')
      .map(([k, v]): [string, string] => [`radius-${k}`, `${v}px`]),
    ...Object.entries(elevation).map(([k, v]): [string, string] => [
      `shadow-${k}`,
      shadowCss(v.shadow),
    ]),
    ...(['bar', 'pill', 'badge', 'scrim'] as const).map((k): [string, string] => [
      `blur-${k}`,
      `${blur[k].radius}px`,
    ]),
    ...Object.entries(breakpoints).map(([k, v]): [string, string] => [`breakpoint-${k}`, rem(v)]),
    ['ease-spring', base.easing],
    ['ease-spring-quick', quick.easing],
    ['ease-out', 'cubic-bezier(0, 0, 0.2, 1)'],
    ...Object.entries(aspect).map(([k, [w, h]]): [string, string] => [
      `aspect-${k}`,
      `${w} / ${h}`,
    ]),
  ]
}

/** Plain variables with no Tailwind namespace: durations, density and TV units. */
function plainEntries(): Entries {
  return [
    ['duration-spring', `${base.duration}ms`],
    ['duration-spring-quick', `${quick.duration}ms`],
    ...Object.entries(durations).map(([k, v]): [string, string] => [
      `duration-${kebab(k)}`,
      `${v}ms`,
    ]),
    ['stagger', '45ms'],
    ...Object.entries(density).map(([k, v]): [string, string] => [`size-${kebab(k)}`, `${v}px`]),
    ['blur-bar-saturate', blur.bar.saturate],
    ['blur-fallback-opacity', blur.fallbackOpacity],
    ['u', '1cqw'],
    ['tv-safe-x', u(tv.safe.x)],
    ['tv-safe-y', u(tv.safe.y)],
    ['tv-poster-width', u(tv.poster.width)],
    ['tv-poster-gap', u(tv.poster.gap)],
    ['tv-radius-poster', u(tv.radius.poster)],
    ['tv-radius-button', u(tv.radius.button)],
    ['tv-radius-pill', u(tv.radius.pill)],
    ['tv-scale-poster', focus.tv.scalePoster],
    ['tv-scale-button', focus.tv.scaleButton],
    ...Object.entries(tvText).flatMap(
      ([k, t]): Entries => [
        [`tv-text-${kebab(k)}`, u(t.size)],
        [`tv-text-${kebab(k)}--line-height`, t.leading],
      ],
    ),
  ]
}

const reducedMotion = `@media (prefers-reduced-motion: reduce) {
${block(
  ':root',
  [
    ['duration-spring', '1ms'],
    ['duration-spring-quick', '1ms'],
    ['stagger', '0ms'],
  ],
  '  ',
)}
}`

/** Framework-free CSS: every token as a custom property, plus one block per built-in theme. */
export function tokensCss(): string {
  const themeIndependent = utilityEntries().filter(([k]) => !k.startsWith('color-'))
  return [
    HEADER,
    themeBlocks(),
    block(':root', [...themeIndependent, ...plainEntries()]),
    reducedMotion,
    '',
  ].join('\n\n')
}

/**
 * A Tailwind v4 theme. Tailwind's default palette, scales and effects are cleared, so only
 * highsea roles and scales produce utilities: `bg-blue-500` doesn't exist here, by design.
 */
export function tailwindCss(): string {
  const resets = [
    'color',
    'font',
    'font-weight',
    'text',
    'tracking',
    'leading',
    'radius',
    'shadow',
    'inset-shadow',
    'drop-shadow',
    'text-shadow',
    'blur',
    'breakpoint',
    'ease',
    'animate',
    'aspect',
  ].map((ns): [string, string] => [`${ns}-*`, 'initial'])
  const theme = block('@theme static', [
    ...resets,
    ...utilityEntries(),
    ['animate-spin', 'spin 1s linear infinite'],
  ]).replace(
    /\n}$/,
    '\n\n  @keyframes spin {\n    to {\n      transform: rotate(360deg);\n    }\n  }\n}',
  )
  return [HEADER, theme, themeBlocks(), block(':root', plainEntries()), reducedMotion, ''].join(
    '\n\n',
  )
}
